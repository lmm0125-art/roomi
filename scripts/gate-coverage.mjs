const rows = [];
let gated = 0;
for (const card of Object.keys(CARD_ALIASES)) {
  const rule = R.CARD_OP_RULES ? R.CARD_OP_RULES[card] : undefined;
  const hasRule = !!rule;
  if (hasRule) gated++;
  const [risk, note] = RISK[card] || ['?', '미분류'];
  const size = rule ? `anchors ${rule.anchors.length} · ops ${rule.badOps.length} · phrases ${rule.phrases.length}` : '—';
  rows.push({ card, hasRule, risk, note, size });
}
const order = { H: 0, M: 1, L: 2, '?': 3 };
rows.sort((a, b) => (order[a.risk] - order[b.risk]) || a.card.localeCompare(b.card, 'ko'));
let out = `# 게이트 커버리지 (v1.85)\n\n카드 ${rows.length}장 · 규칙 있음 ${gated}장 · 규칙 없음 ${rows.length - gated}장\n\n`;
out += '| 카드 | 게이트 규칙 | 위험도 | 이유 | 규칙 크기 |\n|---|---|---|---|---|\n';
for (const r of rows) out += `| ${r.card} | ${r.hasRule ? '있음' : '없음'} | ${r.risk} | ${r.note} | ${r.size} |\n`;
console.log(out);
